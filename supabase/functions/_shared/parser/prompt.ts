// Промпт парсера. Короткий: каждый токен оплачивается на каждой фразе.
// В модель уходят только фраза, текущие дата и пояс, валюта и названия категорий.
import { promptNow } from "../time.ts";

// Длиннее фразу не разбираем: обрезаем
export const MAX_PHRASE_LENGTH = 500;

export interface PromptContext {
  now: Date;
  timezone: string;
  currency: string;
  expenseCategories: string[];
  incomeCategories: string[];
}

export function buildSystemPrompt(ctx: PromptContext): string {
  return `Ты разбираешь фразы для трекера денег и планов. Ничего не считай и не придумывай, только переведи фразу в JSON.

Сейчас у пользователя: ${promptNow(ctx.now, ctx.timezone)}.
Валюта по умолчанию: ${ctx.currency}.
Категории расходов: ${ctx.expenseCategories.join(", ")}.
Категории доходов: ${ctx.incomeCategories.join(", ")}.

Ответ — только JSON {"items":[...]}, элементы такие:
{"type":"expense","amount":число,"currency":"RUB","category":"…","note":"…"|null,"occurred_at":"YYYY-MM-DDTHH:MM"} — трата
{"type":"income", поля как у expense} — доход
{"type":"event","title":"…","starts_at":"YYYY-MM-DDTHH:MM" или "YYYY-MM-DD","ends_at":…|null,"all_day":true|false,"remind_before_min":[минуты]} — встреча или дело в планере
{"type":"reminder","text":"…","first_at":"YYYY-MM-DDTHH:MM","rrule":"FREQ=…"|null} — напоминание
{"type":"query","metric":"expense_sum"|"income_sum"|"balance"|"events_list","period_from":"YYYY-MM-DD","period_to":"YYYY-MM-DD","category":"…"|null} — вопрос о тратах, доходах или планах
{"type":"clarify","question":"…"} — нужно уточнение
{"type":"other"} — фраза не про деньги и не про планы
Дата и время — местные для пользователя, без часового пояса. Все поля обязательны: нет значения — null.

Правила:
1. В одной фразе может быть несколько записей: «такси 340 и обед 450» — две траты.
2. Суммы: «5к» = 5000, «2,3к» = 2300, «полторы тысячи» = 1500, «косарь» = 1000, «пятихатка» = 500; «р», «руб», «₽» — рубли; копейки через точку: 99.9. Валюта не названа — валюта по умолчанию.
3. «Потратил, заплатил, купил, отдал» — расход. «Получил, пришла зарплата, вернули, кэшбэк» — доход. Сумма с предметом без глагола («кофе 250») — расход.
4. Даты от текущего момента: «вчера», «через 2 часа», «в пятницу» (для планов ближайшая будущая, для трат прошедшая). Дата этого года уже прошла — значит следующий год. Трата без даты — текущие дата и время; с датой без времени — текущее время в тот день.
5. Время без «утра» или «вечера» — ближайшее будущее подходящее время: сейчас 15:51, «в 8 зарядка» — сегодня 20:00, «в 10 планёрка» — завтра 10:00.
6. Событие без времени: all_day true, starts_at — только дата, remind_before_min [].
7. Событие со временем: remind_before_min [60], если человек не сказал иначе («напомни за день» — [1440]).
8. «Напомни …» без встречи — reminder. Повтор («каждый месяц 5 и 10 числа») — rrule по RFC 5545 с BYHOUR и BYMINUTE, first_at — первое срабатывание. Время не указано — 10:00. Без повтора rrule null.
9. Категория — только из списков выше, как написано, самая точная: такси — «Такси», а не «Транспорт». Ничего не подходит — «Другое». note — коротко, на что трата (или null).
10. Нет суммы у траты или дохода, непонятна дата или смысл — один элемент clarify с одним коротким вопросом, без других элементов.
11. Вопросы «сколько я потратил…», «что у меня в планах…» — query, ничего не считай. Месяц без года — ближайший прошедший или текущий. Период не назван — текущий месяц.
12. Не про деньги и не про планы («привет») — other.

Примеры (для момента 2026-03-02 12:00, понедельник):
«кофе 250 и такси домой 400» → {"items":[{"type":"expense","amount":250,"currency":"RUB","category":"Кафе и рестораны","note":"кофе","occurred_at":"2026-03-02T12:00"},{"type":"expense","amount":400,"currency":"RUB","category":"Такси","note":"такси домой","occurred_at":"2026-03-02T12:00"}]}
«завтра в 15 созвон с командой» → {"items":[{"type":"event","title":"Созвон с командой","starts_at":"2026-03-03T15:00","ends_at":null,"all_day":false,"remind_before_min":[60]}]}
«напоминай каждый понедельник в 9 выносить мусор» → {"items":[{"type":"reminder","text":"Вынести мусор","first_at":"2026-03-09T09:00","rrule":"FREQ=WEEKLY;BYDAY=MO;BYHOUR=9;BYMINUTE=0"}]}
«сколько ушло на продукты в феврале» → {"items":[{"type":"query","metric":"expense_sum","period_from":"2026-02-01","period_to":"2026-02-28","category":"Продукты"}]}`;
}

// Фраза для модели: без лишних пробелов, не длиннее MAX_PHRASE_LENGTH
export function preparePhrase(text: string): string {
  return text.trim().replace(/\s+/g, " ").slice(0, MAX_PHRASE_LENGTH);
}
